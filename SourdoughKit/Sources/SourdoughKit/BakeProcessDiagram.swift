import Foundation

/// The process as a diagram: walked from the definition (`BakeProcess.nodes`),
/// not from sample setups, so every branch is in it with its condition.
extension BakeProcess {
    /// The label of the branch taken when no rule holds.
    static let otherwiseLabel = "sonst"

    /// The process as a PlantUML activity diagram, for `docs/ablauf.puml`
    /// (`tools/diagrams.sh` draws `docs/ablauf.svg` from it).
    ///
    /// Every step shows the title of its text. Where a step has rules, a
    /// branch per rule carries its condition (`Condition.label`), the last
    /// one "sonst". A decision is followed by its answers: a loop back
    /// through what to do meanwhile for an answer that waits, a branch per
    /// answer otherwise. Rests are grey.
    public static func plantUML() -> String {
        var lines = [
            "@startuml",
            "' Generated by BakeProcess.plantUML() from the definition in SourdoughKit.",
            "' Do not edit: tools/diagrams.sh writes it anew and draws ablauf.svg.",
            "title Ablauf eines Brotback-Durchgangs",
            "start",
        ]
        for node in nodes {
            switch node {
            case .rest(_, let name):
                lines.append(":Ruhe: \(name); <<#E8E8E8>>")
            case .step(let step):
                lines += umlLines(of: step)
            }
        }
        lines += ["stop", "@enduml"]
        return lines.joined(separator: "\n") + "\n"
    }

    /// The label of the loop over the rounds of a step within a rest.
    static let nextRoundLabel = "weitere Runde"

    private static func umlLines(of step: Step) -> [String] {
        let overlaps = if case .action(_, overlapsRest: true) = step.timing { true } else { false }
        var within: String?
        if case .withinRest(let rest) = step.timing { within = restName(rest) }
        var lines: [String]
        if step.variants.rules.isEmpty {
            lines = umlLines(of: step.variants.otherwise, overlaps: overlaps, within: within)
        } else {
            lines = ["switch ()"]
            for branch in step.variants.branches {
                lines.append("case (\(branch.condition?.label ?? otherwiseLabel))")
                lines += umlLines(of: branch.value, overlaps: overlaps, within: within).map { "  " + $0 }
            }
            lines.append("endswitch")
        }
        // Rounds repeat as often as the schedule plans them.
        if within != nil {
            lines = ["repeat"] + lines.map { "  " + $0 } + ["repeat while (\(nextRoundLabel)) is (ja) not (nein)"]
        }
        if let skipped = step.skippedWhen {
            lines = ["if (\(skipped.label)) then (ja)", "else (\(otherwiseLabel))"] + lines.map { "  " + $0 }
                + ["endif"]
        }
        return lines
    }

    /// The German name of `rest` as the nodes give it.
    static func restName(_ rest: RestKind) -> String {
        nodes.lazy.compactMap { node in
            if case .rest(rest, let name) = node { name } else { nil }
        }.first!
    }

    private static func umlLines(of variant: Variant, overlaps: Bool, within: String? = nil) -> [String] {
        let note = overlaps ? "\\n//noch während der Ruhe davor//"
            : within.map { "\\n//während der \($0)//" } ?? ""
        let activity = ":\(title(variant.text))\(note);"
        let waiting = variant.answers.filter(\.waits)
        let proceeding = variant.answers.filter { !$0.waits }
        if let wait = variant.wait, !waiting.isEmpty {
            return ["repeat", "  " + activity, "backward :\(title(wait));",
                    "repeat while () is (\(labels(waiting))) not (\(labels(proceeding)))"]
        }
        guard variant.answers.count > 1 else { return [activity] }
        // Answers that all go on: a branch each, which meet again at once.
        let last = variant.answers.count - 1
        let branches = variant.answers.enumerated().map { index, answer in
            index == 0 ? "if () then (\(answer.label))"
                : index < last ? "elseif () then (\(answer.label))" : "else (\(answer.label))"
        }
        return [activity] + branches + ["endif"]
    }

    private static func labels(_ answers: [Answer]) -> String {
        answers.map(\.label).joined(separator: " / ")
    }

    // MARK: Graph

    /// An edge of the process graph: from a node to the next, with the
    /// condition or answer it is taken on.
    struct Edge: Hashable {
        let from: String
        let to: String
        let label: String?
    }

    /// The process as a graph, for checking that every node can be reached:
    /// nodes are "start", "stop", the texts by raw value and the rests as
    /// "rest.<raw value>".
    static func edges() -> [Edge] {
        var edges: [Edge] = []
        var frontier: [(node: String, label: String?)] = [("start", nil)]
        func connect(to node: String, _ label: String?) {
            for source in frontier {
                let joined = [source.label, label].compactMap { $0 }.joined(separator: ", ")
                edges.append(Edge(from: source.node, to: node, label: joined.isEmpty ? nil : joined))
            }
        }
        for node in nodes {
            switch node {
            case .rest(let rest, _):
                connect(to: "rest.\(rest.rawValue)", nil)
                frontier = [("rest.\(rest.rawValue)", nil)]
            case .step(let step):
                // A step that can be left out lets the way past it go on.
                var exits: [(node: String, label: String?)] = step.skippedWhen.map { skipped in
                    frontier.map { ($0.node, [$0.label, skipped.label].compactMap { $0 }.joined(separator: ", ")) }
                } ?? []
                let branches = step.variants.branches
                for branch in branches {
                    let variant = branch.value
                    let name = variant.text.rawValue
                    connect(to: name, branches.count == 1 ? nil : branch.condition?.label ?? otherwiseLabel)
                    let waiting = variant.answers.filter(\.waits)
                    if let wait = variant.wait, !waiting.isEmpty {
                        edges.append(Edge(from: name, to: wait.rawValue, label: labels(waiting)))
                        edges.append(Edge(from: wait.rawValue, to: name, label: nil))
                    }
                    let proceeding = variant.answers.filter { !$0.waits }
                    exits += proceeding.isEmpty ? [(name, nil)] : proceeding.map { (name, $0.label) }
                    if case .withinRest = step.timing {
                        edges.append(Edge(from: name, to: name, label: nextRoundLabel))
                    }
                }
                frontier = exits
            }
        }
        connect(to: "stop", nil)
        return edges
    }
}
